// 7. Calcule o IMC e exiba o valor.

let peso = 98;
let altura = 1.8;

let IMC = peso / (altura * altura);

console.log("--------------------------");
console.log("O seu peso é:", peso);
console.log("A sua altura é:", altura);
console.log("Então o seu IMC é:", IMC.toFixed(2));
console.log("--------------------------");
